#!/bin/sh

ah_skills_sourced=0
if [ -n "${ZSH_VERSION:-}" ]; then
    case "$ZSH_EVAL_CONTEXT" in
        *:file) ah_skills_sourced=1 ;;
    esac
elif [ -n "${BASH_VERSION:-}" ]; then
    (return 0 2>/dev/null) && ah_skills_sourced=1
else
    case "$0" in
        *install.sh) ah_skills_sourced=0 ;;
        *) ah_skills_sourced=1 ;;
    esac
fi

if [ ! -d domains ]; then
    echo "install.sh: запустите из корня ah-skills (не нашёл domains/ здесь)" >&2
    return 1 2>/dev/null || exit 1
fi

if ! command -v go >/dev/null 2>&1; then
    echo "install.sh: нужен go, не найден в PATH — https://go.dev/dl/ (на macOS: brew install go)" >&2
    return 1 2>/dev/null || exit 1
fi

echo "Собираю ah-skills..."
if ! go build -o ah-skills ./tools; then
    echo "install.sh: сборка не удалась" >&2
    return 1 2>/dev/null || exit 1
fi

ah_skills_root="$(pwd)"
case ":$PATH:" in
    *":$ah_skills_root:"*) ;;
    *) export PATH="$ah_skills_root:$PATH" ;;
esac

ah_skills_shquote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

ah_skills_guard_begin="# >>> ah-skills >>>"
ah_skills_guard_end="# <<< ah-skills <<<"
# shellcheck disable=SC2016
ah_skills_guard_line='[ -f "$HOME/.config/ah-skills/env" ] && . "$HOME/.config/ah-skills/env"'
ah_skills_rc_summary=""

ah_skills_ensure_guard() {
    if [ ! -f "$1" ]; then
        if ! touch "$1" 2>/dev/null; then
            echo "install.sh: не удалось создать $1 — пропускаю" >&2
            return 1
        fi
    fi
    if grep -qF "$ah_skills_guard_begin" "$1" 2>/dev/null; then
        ah_skills_rc_summary="$ah_skills_rc_summary $1"
        return 0
    fi
    if ! {
        printf '\n%s\n' "$ah_skills_guard_begin"
        printf '%s\n' "$ah_skills_guard_line"
        printf '%s\n' "$ah_skills_guard_end"
    } >> "$1" 2>/dev/null; then
        echo "install.sh: не удалось дописать $1 — пропускаю" >&2
        return 1
    fi
    ah_skills_rc_summary="$ah_skills_rc_summary $1"
    return 0
}

ah_skills_persisted=0
ah_skills_config_dir="$HOME/.config/ah-skills"
ah_skills_env_file="$ah_skills_config_dir/env"

if [ -z "$HOME" ]; then
    echo "install.sh: \$HOME не задан — PATH не будет сохранён для новых терминалов" >&2
elif ! mkdir -p "$ah_skills_config_dir" 2>/dev/null; then
    echo "install.sh: не удалось создать $ah_skills_config_dir — PATH не будет сохранён для новых терминалов" >&2
else
    ah_skills_old_root=""
    if [ -f "$ah_skills_env_file" ]; then
        ah_skills_old_root=$(sed -n 's/^# ah-skills-root: //p' "$ah_skills_env_file" 2>/dev/null | head -n 1)
    fi
    ah_skills_quoted_root=$(ah_skills_shquote "$ah_skills_root")
    if {
        printf '%s\n' "# Managed by ah-skills install.sh -- safe to delete, regenerated by the next: source install.sh"
        printf '%s\n' "# ah-skills-root: $ah_skills_root"
        printf '%s\n' "export PATH=$ah_skills_quoted_root:\"\$PATH\""
    } > "$ah_skills_env_file" 2>/dev/null; then
        ah_skills_persisted=1
        if [ -n "$ah_skills_old_root" ] && [ "$ah_skills_old_root" != "$ah_skills_root" ]; then
            echo "ah-skills PATH entry updated: $ah_skills_old_root → $ah_skills_root"
        fi
    else
        echo "install.sh: не удалось записать $ah_skills_env_file — PATH не будет сохранён для новых терминалов" >&2
    fi
    unset ah_skills_old_root ah_skills_quoted_root
fi

ah_skills_fish_shell=0
if [ -n "$HOME" ]; then
    case "$SHELL" in
        */zsh)
            ah_skills_ensure_guard "$HOME/.zshrc"
            ;;
        */bash)
            ah_skills_ensure_guard "$HOME/.bash_profile"
            ah_skills_ensure_guard "$HOME/.bashrc"
            ;;
        */fish)
            ah_skills_fish_shell=1
            ;;
        *)
            ah_skills_ensure_guard "$HOME/.profile"
            ;;
    esac
fi

if [ "$ah_skills_sourced" = 1 ]; then
    echo "Готово: ah-skills доступен в этой оболочке ($(command -v ah-skills))."
    if [ "$ah_skills_persisted" = 1 ]; then
        echo "PATH сохранён для новых терминалов: $ah_skills_env_file"
        if [ -n "$ah_skills_rc_summary" ]; then
            echo "  hook добавлен в:$ah_skills_rc_summary"
            echo "Уже открытые другие терминалы нужно обновить ещё одним source install.sh (или открыть новый — дальше подхватится само)."
        elif [ "$ah_skills_fish_shell" != 1 ]; then
            echo "  не удалось добавить hook ни в один rc-файл — новые терминалы PATH не подхватят, см. предупреждения выше." >&2
        fi
    fi
    if [ "$ah_skills_fish_shell" = 1 ]; then
        echo "fish не поддерживается source install.sh напрямую для автообновления PATH — добавьте вручную: fish_add_path $ah_skills_root"
    fi
    echo
    ah-skills list domains
else
    echo "Собрано: ./ah-skills"
    echo "Это дочерний процесс — PATH не может передаться в родительскую оболочку."
    echo "Чтобы ah-skills сразу заработал в ЭТОЙ оболочке — запустите: source install.sh"
    if [ "$ah_skills_persisted" = 1 ] && [ -n "$ah_skills_rc_summary" ]; then
        echo "Для НОВЫХ терминалов PATH уже сохранён (hook в:$ah_skills_rc_summary) — сработает само, без source install.sh."
    fi
    if [ "$ah_skills_fish_shell" = 1 ]; then
        echo "fish не поддерживается source install.sh напрямую — добавьте вручную: fish_add_path $ah_skills_root"
    fi
fi

unset ah_skills_sourced ah_skills_root
unset ah_skills_persisted ah_skills_config_dir ah_skills_env_file ah_skills_fish_shell
unset ah_skills_rc_summary ah_skills_guard_begin ah_skills_guard_end ah_skills_guard_line
unset -f ah_skills_shquote ah_skills_ensure_guard 2>/dev/null
