def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create a Godot 4 project (folders, settings, input map, layers, main scene, autoloads).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("dest", help="Directory to create the project in (created when missing)")
    parser.add_argument("--preset", required=True, choices=PRESETS,
                        help="pixel2d: low-res pixel art | hd2d: 1080p 2D | 3d: lit 3D starter | ui: tool/menu app")
    parser.add_argument("--name", default="", help="Project name (default: the destination folder name)")
    parser.add_argument("--size", default="", metavar="WxH",
                        help="Override the base viewport size, e.g. 480x270")
    parser.add_argument("--autoloads", default="",
                        help="Comma-separated template stems from templates/gdscript to copy and register "
                             "(default: game_manager,save_manager,scene_transition except for --preset ui)")
    parser.add_argument("--no-autoloads", action="store_true", help="Register no autoloads at all")
    parser.add_argument("--with-tests", action="store_true",
                        help="Also run scripts/test/run_tests.py DEST --init-mini")
    parser.add_argument("--godot-bin", default="", help="Godot executable (default: GODOT_BIN or godot)")
    parser.add_argument("--skip-validate", action="store_true",
                        help="Skip the closing validate_project.py pass (the JSON then has validate.skipped)")
    parser.add_argument("--pretty", action="store_true")
    return parser.parse_args(argv)


