def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv if argv is not None else sys.argv[1:])
    godot_bin = args.godot_bin or os.environ.get("GODOT_BIN", "godot")
    dest = Path(args.dest).expanduser().resolve()
    project_file = dest / "project.godot"
    if project_file.is_file():
        return refuse(
            f"{project_file} already exists; scaffold_project.py never writes into an existing project. "
            "Point --dest at a new directory, or edit this one with "
            f"project_batch / scene_batch (see {SKILL_ROOT / 'references/playbooks.md'} section 1).",
            project_path=str(dest))
    if dest.exists() and not dest.is_dir():
        return refuse(f"{dest} exists and is not a directory")
    if shutil.which(godot_bin) is None:
        return refuse(f"Godot executable was not found: {godot_bin}. "
                      "Install Godot 4.7 or pass --godot-bin /path/to/godot.")

    size = parse_size(args.size)
    name = args.name.strip() or dest.name
    if '"' in name or "\n" in name:
        return refuse('--name must not contain quotes or newlines')

    catalog = available_autoloads()
    if args.no_autoloads:
        requested: list[str] = []
    elif args.autoloads.strip():
        requested = [item.strip() for item in args.autoloads.split(",") if item.strip()]
    elif args.preset == "ui":
        requested = []
    else:
        requested = ["game_manager", "save_manager", "scene_transition"]
    unknown = [item for item in requested if item not in catalog]
    if unknown:
        return refuse(
            f"Unknown autoload template(s): {', '.join(unknown)}. "
            f"Templates that declare 'Autoload: YES' in {TEMPLATE_DIR}: {', '.join(sorted(catalog)) or '(none)'}",
            available_autoloads=sorted(catalog))

    config = preset_config(args.preset, name, size)
    created: list[str] = []
    try:
        created += write_skeleton(dest, name, args.preset, config, godot_bin)
        # First import builds .godot/ and imports icon.svg, so the project is a
        # real project before any dispatcher operation touches it.
        run("import", [godot_bin, "--headless", "--path", str(dest), "--import"])

        autoloads = copy_autoloads(dest, requested, catalog)
        created += [f"scripts/{item}.gd" for item in requested]
        if requested:
            # A copied script's `class_name` stays invisible to every other
            # script until --import refreshes .godot/global_script_class_cache.
            run("import", [godot_bin, "--headless", "--path", str(dest), "--import"])

        buses: list[str] = []
        if "AudioManager" in autoloads.values():
            # audio_manager.gd routes to the Music and SFX buses; registering it
            # before they exist makes every player fall back to Master and the
            # validation run carries a warning.
            dispatch(godot_bin, dest, "setup_audio_buses", {
                "buses": [
                    {"name": "Master", "volume_db": 0.0},
                    {"name": "Music", "send": "Master", "volume_db": -6.0},
                    {"name": "SFX", "send": "Master", "volume_db": -3.0},
                ],
                "save_path": "audio/default_bus_layout.tres",
                "set_project_setting": True,
            })
            buses = ["Master", "Music", "SFX"]
            created.append("audio/default_bus_layout.tres")

        actions = settings_actions(config) + input_actions_batch(config) + layer_actions(config)
        for stem, autoload in autoloads.items():
            actions.append({"type": "add_autoload", "autoload_name": autoload,
                            "path": f"res://scripts/{stem}.gd", "singleton": True})
        dispatch(godot_bin, dest, "project_batch", {"actions": actions})

        dispatch(godot_bin, dest, "scene_batch", config["scene"])
        created.append(config["scene_path"])
        dispatch(godot_bin, dest, "project_batch", {
            "actions": [{"type": "set_main_scene", "scene_path": "res://" + config["scene_path"]}]})
        normalize_int_settings(dest / "project.godot", config["settings"])

        tests: dict = {"initialized": False}
        if args.with_tests:
            result = run("run_tests --init-mini",
                         [sys.executable, str(RUN_TESTS_SCRIPT), str(dest), "--init-mini",
                          "--godot-bin", godot_bin])
            tests = {"initialized": True, "detail": last_json(result.stdout) or {}}
            created += ["tests/test_case.gd", "tests/test_example.gd"]

        run("import", [godot_bin, "--headless", "--path", str(dest), "--import"])
    except StepFailure as failure:
        print(json.dumps({"ok": False, "preset": args.preset, "project_path": str(dest),
                          "created": sorted(set(created)), "failed": failure.payload()},
                         indent=2 if args.pretty else None))
        return 1
    except subprocess.TimeoutExpired as expired:
        print(json.dumps({"ok": False, "preset": args.preset, "project_path": str(dest),
                          "error": f"timed out: {expired.cmd}"}, indent=2 if args.pretty else None))
        return 1

    validate: dict = {"skipped": True}
    if not args.skip_validate:
        validate = validate_project(dest, godot_bin)

    payload = {
        "ok": bool(validate.get("ok", True)),
        "preset": args.preset,
        "project_path": str(dest),
        "name": name,
        "created": sorted(set(created)),
        "settings_applied": config["settings"],
        "input_actions": sorted(input_actions(config["actions"])),
        "autoloads": list(autoloads.values()),
        "autoload_scripts": {name: f"res://scripts/{stem}.gd" for stem, name in autoloads.items()},
        "audio_buses": buses,
        "main_scene": "res://" + config["scene_path"],
        "tests": tests,
        "validate": validate,
        "next": next_commands(dest, args.preset),
    }
    print(json.dumps(payload, indent=2 if args.pretty else None))
    return 0 if payload["ok"] else 1


def last_json(stdout: str) -> dict | None:
    for line in reversed(stdout.splitlines()):
        stripped = line.strip()
        if stripped.startswith("{") and stripped.endswith("}"):
            try:
                return json.loads(stripped)
            except json.JSONDecodeError:
                return None
    return None


def write_skeleton(dest: Path, name: str, preset: str, config: dict, godot_bin: str) -> list[str]:
    created: list[str] = []
    dest.mkdir(parents=True, exist_ok=True)
    for folder in config["folders"]:
        (dest / folder).mkdir(parents=True, exist_ok=True)
        # Git drops empty directories; a dot-file is also skipped by Godot's
        # filesystem scanner, so it never shows up as an unimportable asset.
        (dest / folder / ".gitkeep").write_text("", encoding="utf-8")
        created.append(folder + "/")

    version = godot_version(godot_bin)
    features = f'PackedStringArray("{version}", "{config["features"]}")'
    (dest / "project.godot").write_text(
        "; Engine configuration file.\n"
        "; Written by scripts/project/scaffold_project.py, then rewritten by\n"
        "; ProjectSettings.save() through the project_batch operation.\n"
        "\n"
        "config_version=5\n"
        "\n"
        "[application]\n"
        "\n"
        f'config/name="{name}"\n'
        f"config/features={features}\n"
        'config/icon="res://icon.svg"\n',
        encoding="utf-8")
    created.append("project.godot")
    (dest / "icon.svg").write_text(ICON_SVG, encoding="utf-8")
    created.append("icon.svg")
    (dest / ".gitignore").write_text(GITIGNORE, encoding="utf-8")
    created.append(".gitignore")
    (dest / ".gitattributes").write_text(GITATTRIBUTES, encoding="utf-8")
    created.append(".gitattributes")
    (dest / "scenarios").mkdir(parents=True, exist_ok=True)
    (dest / "scenarios/boot_check.json").write_text(
        json.dumps(boot_scenario(preset), indent=2) + "\n", encoding="utf-8")
    created.append("scenarios/boot_check.json")
    return created


def normalize_int_settings(project_file: Path, settings: dict) -> None:
    """Rewrite ``viewport_width=320.0`` back to ``viewport_width=320``.

    JSON has a single number type, so every integer that travels through the
    dispatcher arrives in GDScript as a float and ``ProjectSettings.save()``
    writes ``320.0`` where the editor writes ``320``. The engine converts on
    read, so nothing breaks — but the file is what the next human and the next
    agent copy from, so it should say what the editor says. This runs after the
    last ``project_batch``; once the file holds an int, Godot loads it as an int
    and every later save keeps it.
    """
    wanted: dict[tuple[str, str], int] = {}
    for name, value in settings.items():
        if isinstance(value, bool) or not isinstance(value, int) or "/" not in name:
            continue
        section, _, key = name.partition("/")
        wanted[(section, key)] = value
    if not wanted or not project_file.is_file():
        return
    section = ""
    out: list[str] = []
    changed = False
    for line in project_file.read_text(encoding="utf-8").splitlines(keepends=True):
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            section = stripped[1:-1]
        elif "=" in stripped and not stripped.startswith(";"):
            key = stripped.split("=", 1)[0].strip()
            target = wanted.get((section, key))
            if target is not None and stripped.split("=", 1)[1].strip() == f"{float(target)!r}":
                line = f"{key}={target}\n"
                changed = True
        out.append(line)
    if changed:
        project_file.write_text("".join(out), encoding="utf-8")


def copy_autoloads(dest: Path, requested: list[str], catalog: dict[str, str]) -> dict[str, str]:
    autoloads: dict[str, str] = {}
    scripts = dest / "scripts"
    scripts.mkdir(parents=True, exist_ok=True)
    for stem in requested:
        shutil.copyfile(TEMPLATE_DIR / f"{stem}.gd", scripts / f"{stem}.gd")
        autoloads[stem] = catalog[stem]
    return autoloads


def settings_actions(config: dict) -> list[dict]:
    return [{"type": "set_setting", "name": key, "value": value}
            for key, value in config["settings"].items()]


def input_actions_batch(config: dict) -> list[dict]:
    actions: list[dict] = []
    for action_name, events in sorted(input_actions(config["actions"]).items()):
        actions.append({"type": "add_input_action", "action_name": action_name, "replace": True})
        for event in events:
            actions.append({"type": "add_input_event", "action_name": action_name, "event": event})
    return actions


def layer_actions(config: dict) -> list[dict]:
    kind = config["layers"]
    if kind == "none":
        return []
    physics = f"{kind}_physics"
    render = f"{kind}_render"
    names = RENDER_LAYERS_2D if kind == "2d" else RENDER_LAYERS_3D
    actions = [{"type": "set_layer_name", "layer_type": physics, "layer": index + 1, "layer_name": layer}
               for index, layer in enumerate(PHYSICS_LAYERS)]
    actions += [{"type": "set_layer_name", "layer_type": render, "layer": index + 1, "layer_name": layer}
                for index, layer in enumerate(names)]
    return actions


def validate_project(dest: Path, godot_bin: str) -> dict:
    # --warnings-as-errors: a scaffold that starts with yellow triangles teaches
    # the agent to ignore them.
    result = subprocess.run([sys.executable, str(VALIDATE_SCRIPT), str(dest),
                             "--godot-bin", godot_bin, "--warnings-as-errors"],
                            capture_output=True, text=True, check=False, timeout=600)
    payload = last_json(result.stdout)
    if payload is None:
        return {"ok": False, "counts": {}, "error": tail(result.stderr) or tail(result.stdout)}
    return {"ok": bool(payload.get("ok")), "counts": payload.get("counts", {}),
            "diagnostics": payload.get("diagnostics", [])[:10]}


