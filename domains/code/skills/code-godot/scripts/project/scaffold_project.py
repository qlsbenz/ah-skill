def input_actions(kind: str) -> dict:
    """action name -> list of typed InputEvent payloads."""
    movement = {
        "move_left": [key_event(KEY["A"]), key_event(KEY["LEFT"]),
                      pad_button(JOY_BUTTON["DPAD_LEFT"]), pad_axis(JOY_AXIS["LEFT_X"], -1.0)],
        "move_right": [key_event(KEY["D"]), key_event(KEY["RIGHT"]),
                       pad_button(JOY_BUTTON["DPAD_RIGHT"]), pad_axis(JOY_AXIS["LEFT_X"], 1.0)],
        "move_up": [key_event(KEY["W"]), key_event(KEY["UP"]),
                    pad_button(JOY_BUTTON["DPAD_UP"]), pad_axis(JOY_AXIS["LEFT_Y"], -1.0)],
        "move_down": [key_event(KEY["S"]), key_event(KEY["DOWN"]),
                      pad_button(JOY_BUTTON["DPAD_DOWN"]), pad_axis(JOY_AXIS["LEFT_Y"], 1.0)],
    }
    common = {
        "interact": [key_event(KEY["E"]), pad_button(JOY_BUTTON["X"])],
        "pause": [key_event(KEY["ESCAPE"]), pad_button(JOY_BUTTON["START"])],
    }
    if kind == "ui":
        return common
    actions = dict(movement)
    actions["jump"] = [key_event(KEY["SPACE"]), pad_button(JOY_BUTTON["A"])]
    actions["attack"] = [key_event(KEY["J"]), pad_button(JOY_BUTTON["B"])]
    actions.update(common)
    return actions


# --- helpers ----------------------------------------------------------------

class StepFailure(Exception):
    def __init__(self, step: str, command: list[str], returncode: int, stdout: str, stderr: str):
        super().__init__(step)
        self.step = step
        self.command = command
        self.returncode = returncode
        self.stdout = stdout
        self.stderr = stderr

    def payload(self) -> dict:
        return {
            "step": self.step,
            "command": " ".join(self.command),
            "returncode": self.returncode,
            "stderr": tail(self.stderr) or tail(self.stdout),
        }


def tail(text: str, lines: int = 12) -> str:
    kept = [line for line in text.splitlines() if line.strip()]
    return "\n".join(kept[-lines:])


def run(step: str, command: list[str], timeout: float = 300.0) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(command, capture_output=True, text=True, check=False, timeout=timeout)
    if result.returncode != 0:
        raise StepFailure(step, command, result.returncode, result.stdout, result.stderr)
    return result


def dispatch(godot_bin: str, project: Path, operation: str, params: dict) -> dict:
    command = [godot_bin, "--headless", "--path", str(project), "--script", str(DISPATCHER),
               operation, json.dumps(params, separators=(",", ":"))]
    result = run(operation, command)
    # Not every operation prints a payload (scene_batch only logs), and the
    # dispatcher already exited non-zero if anything went wrong.
    return last_json(result.stdout) or {}


def godot_version(godot_bin: str) -> str:
    try:
        out = subprocess.run([godot_bin, "--version"], capture_output=True, text=True,
                             check=False, timeout=30).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return "4.7"
    match = re.match(r"^(\d+\.\d+)", out)
    return match.group(1) if match else "4.7"


def autoload_name_for(template: Path) -> str | None:
    """`# Autoload: YES, as \\`GameManager\\`` in the template header, or None.

    Reading the name out of the file keeps this in step with templates other
    work packages add, instead of a table here that silently goes stale.
    """
    try:
        header = template.read_text(encoding="utf-8")[:4000]
    except OSError:
        return None
    match = re.search(r"#\s*Autoload:\s*YES,\s*as\s*`([A-Za-z_][A-Za-z0-9_]*)`", header)
    if match:
        return match.group(1)
    if re.search(r"#\s*Autoload:\s*YES", header):
        return "".join(part.capitalize() for part in template.stem.split("_"))
    return None


def available_autoloads() -> dict[str, str]:
    found: dict[str, str] = {}
    if not TEMPLATE_DIR.is_dir():
        return found
    for template in sorted(TEMPLATE_DIR.glob("*.gd")):
        name = autoload_name_for(template)
        if name:
            found[template.stem] = name
    return found


def parse_size(raw: str) -> tuple[int, int] | None:
    if not raw:
        return None
    match = re.fullmatch(r"\s*(\d+)\s*[xX*]\s*(\d+)\s*", raw)
    if not match:
        raise SystemExit(refuse(f"--size must look like WxH, e.g. 320x180 (got: {raw!r})"))
    width, height = int(match.group(1)), int(match.group(2))
    if width < 16 or height < 16 or width > 16384 or height > 16384:
        raise SystemExit(refuse(f"--size must be between 16x16 and 16384x16384 (got: {width}x{height})"))
    return width, height


def refuse(message: str, **extra: object) -> int:
    payload = {"ok": False, "error": message}
    payload.update(extra)
    print(json.dumps(payload, indent=2))
    return 2


