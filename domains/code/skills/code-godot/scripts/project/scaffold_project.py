def boot_scenario(preset: str) -> dict:
    """A ready-to-run scenario that proves the main scene renders something.

    Written into the project as ``scenarios/boot_check.json`` so the closing
    ``next[]`` command is copy-paste runnable instead of a JSON blob to retype.
    """
    if preset == "3d":
        return {
            "scene_path": "scenes/main.tscn",
            "steps": [
                {"type": "spatial_report", "label": "boot", "ascii": True,
                 # Both of these render a black frame with no error at all,
                 # which is the single most common "my 3D scene is broken".
                 "fail_on": ["no_camera_3d", "no_light_3d"]},
            ],
        }
    if preset == "ui":
        return {
            "scene_path": "scenes/main.tscn",
            "viewport_size": {"width": 1280, "height": 720},
            "steps": [
                {"type": "ui_report", "label": "boot", "ascii": True, "fail_on": ["any"]},
            ],
        }
    return {
        "scene_path": "scenes/main.tscn",
        "steps": [
            {"type": "dump_tree", "label": "boot", "properties": ["visible", "position"]},
            {"type": "spatial_report", "label": "boot", "ascii": True},
        ],
    }


